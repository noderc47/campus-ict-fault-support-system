package com.campusict.model;

import java.time.LocalDateTime;

/**
 * Represents one fault report from the tickets table.
 */
public class Ticket {

    private Integer ticketId;
    private Integer reporterId;
    private String reporterName;
    private String category;
    private String location;
    private String description;
    private String urgency;
    private String status;
    private Integer assignedTechId;
    private String technicianName;
    private String resolutionNotes;
    private LocalDateTime resolvedAt;
    private LocalDateTime dateReported;
    private LocalDateTime updatedAt;

    /**
     * Creates an empty ticket object.
     */
    public Ticket() {
    }

    /**
     * Creates a ticket object with the values needed by the Report Fault form.
     *
     * @param ticketId generated MySQL primary key
     * @param reporterId user ID of the reporter
     * @param reporterName reporter name from the users table join
     * @param category fault category
     * @param location reported location
     * @param description fault description
     * @param urgency fault urgency
     * @param status ticket status
     * @param dateReported timestamp generated by MySQL
     */
    public Ticket(Integer ticketId, Integer reporterId, String reporterName, String category, String location,
                  String description, String urgency, String status, LocalDateTime dateReported) {
        this(ticketId, reporterId, reporterName, category, location, description, urgency, status,
                null, null, null, null, dateReported, null);
    }

    /**
     * Creates a ticket object with all fields used by Report Fault and Search & Manage Tickets.
     */
    public Ticket(Integer ticketId, Integer reporterId, String reporterName, String category, String location,
                  String description, String urgency, String status, Integer assignedTechId, String technicianName,
                  String resolutionNotes, LocalDateTime resolvedAt, LocalDateTime dateReported,
                  LocalDateTime updatedAt) {
        this.ticketId = ticketId;
        this.reporterId = reporterId;
        this.reporterName = reporterName;
        this.category = category;
        this.location = location;
        this.description = description;
        this.urgency = urgency;
        this.status = status;
        this.assignedTechId = assignedTechId;
        this.technicianName = technicianName;
        this.resolutionNotes = resolutionNotes;
        this.resolvedAt = resolvedAt;
        this.dateReported = dateReported;
        this.updatedAt = updatedAt;
    }

    public Integer getTicketId() {
        return ticketId;
    }

    public void setTicketId(Integer ticketId) {
        this.ticketId = ticketId;
    }

    public Integer getReporterId() {
        return reporterId;
    }

    public void setReporterId(Integer reporterId) {
        this.reporterId = reporterId;
    }

    public String getReporterName() {
        return reporterName;
    }

    public void setReporterName(String reporterName) {
        this.reporterName = reporterName;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    public String getLocation() {
        return location;
    }

    public void setLocation(String location) {
        this.location = location;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getUrgency() {
        return urgency;
    }

    public void setUrgency(String urgency) {
        this.urgency = urgency;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public Integer getAssignedTechId() {
        return assignedTechId;
    }

    public void setAssignedTechId(Integer assignedTechId) {
        this.assignedTechId = assignedTechId;
    }

    public String getTechnicianName() {
        return technicianName;
    }

    public void setTechnicianName(String technicianName) {
        this.technicianName = technicianName;
    }

    public String getResolutionNotes() {
        return resolutionNotes;
    }

    public void setResolutionNotes(String resolutionNotes) {
        this.resolutionNotes = resolutionNotes;
    }

    public LocalDateTime getResolvedAt() {
        return resolvedAt;
    }

    public void setResolvedAt(LocalDateTime resolvedAt) {
        this.resolvedAt = resolvedAt;
    }

    public LocalDateTime getDateReported() {
        return dateReported;
    }

    public void setDateReported(LocalDateTime dateReported) {
        this.dateReported = dateReported;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(LocalDateTime updatedAt) {
        this.updatedAt = updatedAt;
    }
}